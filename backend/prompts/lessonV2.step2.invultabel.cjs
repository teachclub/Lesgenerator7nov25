// Sectie 5 – invultabel (landscape-werkblad)

function buildInvultabelSection() {
  return `
==================================================
INVULTABEL – LANDSCAPE-WERKBLAD
==================================================

DE TABEL IS BEDOELD ALS LOS LANDSCAPE-VEL.

STRUCTUUR:
- 3 kolommen:
  1) "Belangrijkste observaties"
  2) "Interpretatie"
  3) "Link met hoofdvraag"

OMSCHRIJVINGEN:
- Geef per kolom een korte beschrijving (1–2 zinnen) in leerlingtaal:
  - "Belangrijkste observaties":
    - hier noteer je opvallende details uit de bron (personen, beelden, woorden, gebeurtenissen).
  - "Interpretatie":
    - hier noteer je wat die details betekenen in de tijd van toen
      (ideeën, angsten, belangen, machtsverhoudingen).
  - "Link met hoofdvraag":
    - hier schrijf je kort hoe jouw observaties en interpretatie laten zien
      waarom mensen in die tijd een dreiging, maatregel of ontwikkeling
      als normaal, logisch of noodzakelijk konden ervaren.

HOUD HET KORT:
- Dit is een invulhulp, geen plaats voor lange uitleg.
`;
}

module.exports = buildInvultabelSection;

